"""WebP copies of the catalogue photos for the <img appPhoto> directive.

Run from frontend/:  python3 scripts/optimize-images.py   (needs Pillow)
Reads every /assets/cases/... path quoted in src/app/data/products.static.ts, writes
public/assets/opt/<slug>-<width>.webp (480/960/1600, never upscaled) and regenerates
src/app/core/images/optimized-images.ts. Originals are left untouched.
"""
import json, os, re
from PIL import Image, ImageOps

src = open('src/app/data/products.static.ts', encoding='utf-8').read()
used = sorted(set(re.findall(r"'(/assets/cases/[^']+\.(?:jpe?g|png|JPE?G|PNG))'", src)))
out_dir = 'public/assets/opt'
os.makedirs(out_dir, exist_ok=True)
manifest = {}
for u in used:
    p = 'public' + u
    if not os.path.exists(p):
        print('missing', u)
        continue
    im = ImageOps.exif_transpose(Image.open(p))
    alpha = im.mode in ('RGBA', 'LA') or (im.mode == 'P' and 'transparency' in im.info)
    im = im.convert('RGBA' if alpha else 'RGB')
    slug = re.sub(r'[^A-Za-z0-9]+', '-', u[len('/assets/cases/'):].rsplit('.', 1)[0]).strip('-').lower()
    widths = [w for w in (480, 960, 1600) if w < im.width] or [im.width]
    for w in widths:
        h = round(im.height * w / im.width)
        im.resize((w, h), Image.LANCZOS).save(f'{out_dir}/{slug}-{w}.webp', 'WEBP', quality=76, method=6)
    manifest[u] = {'slug': slug, 'widths': widths, 'ratio': round(im.width / im.height, 4)}

with open('src/app/core/images/optimized-images.ts', 'w') as f:
    f.write('// Generated by scripts/optimize-images.py — WebP copies of the catalogue photos.\n')
    f.write('// Key: original path. Do not edit by hand; re-run the script after adding photos.\n')
    f.write('export const OPTIMIZED_IMAGES: Record<string, { slug: string; widths: number[]; ratio: number }> = ')
    f.write(json.dumps(manifest, indent=2) + ';\n')
print(len(manifest), 'photos optimised')
